package cli

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/ViitoJooj/devx/internal/cli/config"
	"github.com/ViitoJooj/devx/internal/cli/utils"
	"github.com/ViitoJooj/devx/pkg/errorx"
	"github.com/spf13/cobra"
)

var migrateCmd = &cobra.Command{
	Use:   "migrate",
	Short: "Move a project generated by an older devx to the current layout (internal/restful, internal/config, internal/shared, pkg/database, pkg/cache)",
	Args:  cobra.NoArgs,
	Run:   migrate,
}

// layoutMoves are the folders of the old layout and where they live now; imports follow the same prefixes.
var layoutMoves = [][2]string{
	{"internal/containers", "internal/restful"},
	{"pkg/dotenv", "internal/config"},
	{"pkg/logs", "internal/shared/logs"},
	{"pkg/utils", "internal/shared/utils"},
	{"pkg/httpx", "internal/shared/httpx"},
	{"pkg/errorx", "internal/shared/errorx"},
	{"pkg/postgres", "pkg/database/postgres"},
	{"pkg/migration", "pkg/database/postgres/migration"},
	{"pkg/redis", "pkg/cache/redis"},
}

var dotenvIdent = regexp.MustCompile(`(^|[^A-Za-z0-9_])dotenv\.`)

func migrate(cmd *cobra.Command, args []string) {

	project, err := config.LoadProject()
	if err != nil {
		errorx.NotInProject()
	}

	if !isLegacyLayout(project) {
		fmt.Println("project already uses the current layout")
		return
	}

	if err := utils.Step("moving to the current layout", func() error { return migrateLayout(project) }); err != nil {
		errorx.CannotGenerate(err)
	}

	if err := utils.Step("go mod tidy", func() error { return utils.RunGo(project.Root, "mod", "tidy") }); err != nil {
		errorx.CannotRunGo(err)
	}

	fmt.Println("project migrated; review the changes with git diff")
}

// isLegacyLayout is a project generated before the restful/config/shared layout.
func isLegacyLayout(project *config.Project) bool {
	return project.Exists("internal", "containers") ||
		project.Exists("pkg", "dotenv") ||
		project.Exists("pkg", "errorx", "config_errors.go")
}

func migrateLayout(project *config.Project) error {

	hadConfig := project.Exists("pkg", "dotenv", "dotenv.go")

	for _, move := range layoutMoves {
		from := project.Path(filepath.FromSlash(move[0]))
		to := project.Path(filepath.FromSlash(move[1]))

		if _, err := os.Stat(from); err != nil {
			continue
		}

		if err := moveDir(from, to); err != nil {
			return err
		}

		if err := rewriteImports(project.Root, project.Module+"/"+move[0], project.Module+"/"+move[1]); err != nil {
			return err
		}
	}

	if !hadConfig {
		return nil
	}

	if err := os.Rename(project.Path("internal", "config", "dotenv.go"), project.Path("internal", "config", "config.go")); err != nil {
		return err
	}

	configImport := `"` + project.Module + `/internal/config"`

	return rewriteGo(project.Root, func(path, src string) string {

		if filepath.Base(path) == "config.go" && filepath.Base(filepath.Dir(path)) == "config" && strings.Contains(src, "package dotenv") {
			src = strings.Replace(src, "package dotenv", "package config", 1)
			return strings.Replace(src, "func NewDotenv(", "func New(", 1)
		}

		if !strings.Contains(src, configImport) {
			return src
		}

		src = dotenvIdent.ReplaceAllString(src, "${1}config.")
		return strings.ReplaceAll(src, "config.NewDotenv(", "config.New(")
	})
}

// moveDir moves from to to, merging into it when it already exists (pkg/utils and pkg/errorx may be shared by api and cli).
func moveDir(from, to string) error {

	if err := os.MkdirAll(filepath.Dir(to), 0o755); err != nil {
		return err
	}

	if _, err := os.Stat(to); err != nil {
		return os.Rename(from, to)
	}

	entries, err := os.ReadDir(from)
	if err != nil {
		return err
	}

	for _, entry := range entries {
		if err := moveDir(filepath.Join(from, entry.Name()), filepath.Join(to, entry.Name())); err != nil {
			return err
		}
	}

	return os.Remove(from)
}
