package cli

import (
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/ViitoJooj/devx/internal/cli/config"
	"github.com/ViitoJooj/devx/internal/cli/utils"
	"github.com/ViitoJooj/devx/internal/templates"
)

const (
	composeCmd = "$(COMPOSE)"

	devFile = "dev.mk"
	dbFile  = "db.mk"

	generatedHeader = "# generated by devx: edit the makefile (or add another .mk) for your own targets\n"
)

var managedTargets = []string{"run-dev", "run-api", "run-build", "docker-restart", "run-docker", "sudo-clean", "run-cli", "build-cli", "run-mcp", "build-mcp", "run-jobs", "build-jobs"}

type makeRule struct {
	Targets string
	Content string
}

func makePath(project *config.Project, file string) string {
	return project.Path("hacks", "make", file)
}

// syncMakefile rewrites hacks/make/dev.mk and db.mk from the project state; env.mk and the makefile are created once and kept.
func syncMakefile(project *config.Project) error {

	if err := ensureMakeBase(project); err != nil {
		return err
	}

	if err := writeMakeFile(makePath(project, devFile), desiredRules(project)); err != nil {
		return err
	}

	rules := dbRules(project)
	if len(rules) == 0 {
		err := os.Remove(makePath(project, dbFile))
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}

	return writeMakeFile(makePath(project, dbFile), rules)
}

// ensureMakeBase creates env.mk and the makefile when missing, and moves old projects (rules written straight in the makefile) to the includes.
func ensureMakeBase(project *config.Project) error {

	if !project.Exists("hacks", "make", "env.mk") {
		if err := writeBase("base/hacks/make/env.mk.tmpl", project.Path("hacks", "make", "env.mk")); err != nil {
			return err
		}
	}

	if !project.Exists("makefile") {
		return writeBase("base/makefile.tmpl", project.Path("makefile"))
	}

	data, err := os.ReadFile(project.Path("makefile"))
	if err != nil || strings.Contains(string(data), "hacks/make/env.mk") {
		return err
	}

	base, err := templates.FS.ReadFile("base/makefile.tmpl")
	if err != nil {
		return err
	}

	return migrateMakefile(project, string(base))
}

func writeBase(source, dest string) error {

	content, err := templates.FS.ReadFile(source)
	if err != nil {
		return err
	}

	return utils.WriteNewFile(dest, string(content))
}

// migrateMakefile drops the rules devx used to own and puts the includes on top, keeping everything written by hand.
func migrateMakefile(project *config.Project, base string) error {

	path := project.Path("makefile")

	err := utils.MakeRemoveRules(path, func(targets string) bool { return managedTarget(targets) })
	if err != nil {
		return err
	}

	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	includes, _, _ := strings.Cut(base, "\n\n")
	rest := strings.TrimSpace(string(data))

	content := includes + "\n"
	if rest != "" {
		content += "\n" + rest + "\n"
	}

	return os.WriteFile(path, []byte(content), 0o644)
}

func writeMakeFile(path string, rules []makeRule) error {

	var targets []string
	var body []string
	for _, rule := range rules {
		targets = append(targets, strings.Fields(rule.Targets)...)
		body = append(body, rule.Content)
	}

	content := generatedHeader + ".PHONY: " + strings.Join(targets, " ") + "\n\n" + strings.Join(body, "\n\n") + "\n"

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}

	return os.WriteFile(path, []byte(content), 0o644)
}

func managedTarget(targets string) bool {

	if targets == ".PHONY" || slices.Contains(managedTargets, targets) || strings.HasPrefix(targets, "view-") {
		return true
	}

	for target := range strings.FieldsSeq(targets) {
		if !slices.Contains(cleanNames(), target) {
			return false
		}
	}
	return true
}

func cleanNames() []string {
	var names []string
	for _, name := range serviceOrder {
		if clean := services[name].Clean; clean != nil {
			names = append(names, clean.Name)
		}
	}
	return names
}

func desiredRules(project *config.Project) []makeRule {

	var rules []makeRule

	if project.HasAPI() {
		rules = append(rules, apiRules(project)...)
	}

	for _, kind := range []string{"cli", "mcp", "jobs"} {
		if !project.Has(kind) {
			continue
		}

		pkg := "."
		if !project.Standalone() {
			pkg = "./cmd/" + kind
		}

		args := ""
		if kind == "cli" {
			args = " $(ARGS)"
		}

		binary := project.Name
		if kind != "cli" {
			binary += "-" + kind
		}

		rules = append(rules,
			makeRule{"run-" + kind, "run-" + kind + ":\n\tgo run " + pkg + args},
			makeRule{"build-" + kind, "build-" + kind + ":\n\tgo build -o ./tmp/" + binary + " " + pkg},
		)
	}

	return rules
}

func apiRules(project *config.Project) []makeRule {

	compose := project.Exists("infra", "compose", "docker-compose.yaml")
	installed := installedViews(project)

	runDev := "run-dev:"
	if compose {
		runDev += "\n\t" + composeCmd + " up -d"
	}

	var viewTargets []string
	for _, info := range installed {
		viewTargets = append(viewTargets, "view-"+info.Name)
	}

	if len(viewTargets) > 0 {
		runDev += "\n\t$(MAKE) -j run-api " + strings.Join(viewTargets, " ")
	} else {
		runDev += "\n\tgo run ./cmd/api"
	}

	rules := []makeRule{{"run-dev", runDev}}

	if len(viewTargets) > 0 {
		rules = append(rules, makeRule{"run-api", "run-api:\n\tgo run ./cmd/api"})
	}

	rules = append(rules, makeRule{"run-build", "run-build:\n\tgo build -o ./tmp/main ./cmd/api"})

	if compose {
		rules = append(rules, makeRule{"docker-restart", "docker-restart:\n\t" + composeCmd + " down\n\t" + composeCmd + " up -d"})
	}

	if project.Exists(dockerService.detectPath()...) {
		rules = append(rules, makeRule{"run-docker", "run-docker:\n\t" + composeCmd + " --profile app up -d --build"})
	}

	for _, info := range installed {
		rules = append(rules, makeRule{"view-" + info.Name, "view-" + info.Name + ":\n\tcd www/" + info.Name + " && bun install && " + views[info.Kind].Dev})
	}

	return rules
}

// dbRules are the clean targets of the services in the project.
func dbRules(project *config.Project) []makeRule {

	var targets []cleanTarget
	for _, name := range serviceOrder {
		svc := services[name]
		if svc.Clean != nil && project.Exists(svc.detectPath()...) {
			targets = append(targets, *svc.Clean)
		}
	}

	var rules []makeRule

	if len(targets) > 0 {
		var names []string
		for _, target := range targets {
			names = append(names, target.Name)
		}

		rules = append(rules,
			makeRule{"sudo-clean", sudoCleanRule(targets)},
			makeRule{strings.Join(names, " "), strings.Join(names, " ") + ":\n\t@:"},
		)
	}

	return rules
}

func sudoCleanRule(targets []cleanTarget) string {

	var names []string
	var cases strings.Builder

	for _, target := range targets {
		names = append(names, target.Name)

		cases.WriteString("\t\t\t" + target.Name + ") \\\n")
		for line := range strings.SplitSeq(target.Script, "\n") {
			cases.WriteString("\t\t\t\t" + line + "\n")
		}
		cases.WriteString("\t\t\t\t;; \\\n")
	}

	list := strings.Join(names, " ")
	options := strings.Join(names, "|")

	return "sudo-clean:\n" +
		"\t@targets=\"$(filter-out sudo-clean,$(MAKECMDGOALS))\"; \\\n" +
		"\tif [ -z \"$$targets\" ]; then \\\n" +
		"\t\techo \"uso: make sudo-clean " + options + " [" + list + "]\"; \\\n" +
		"\t\texit 1; \\\n" +
		"\tfi; \\\n" +
		"\tfor target in $$targets; do \\\n" +
		"\t\tcase \"$$target\" in \\\n" +
		cases.String() +
		"\t\t\t*) \\\n" +
		"\t\t\t\techo \"arg desconhecido: $$target (use " + options + ")\"; \\\n" +
		"\t\t\t\texit 1; \\\n" +
		"\t\t\t\t;; \\\n" +
		"\t\tesac; \\\n" +
		"\tdone"
}
